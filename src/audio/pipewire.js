import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import Gvc from 'gi://Gvc';
import {EventEmitter} from 'resource:///org/gnome/shell/misc/signals.js';

import {EQ_BANDS, BASS_NODE, TREBLE_NODE} from './presets.js';
import {clamp, roundToStep, shortenDeviceName, Logger} from '../utils/helpers.js';

export const BackendStatus = {
    DISABLED: 'disabled',
    STARTING: 'starting',
    READY: 'ready',
    UNAVAILABLE: 'unavailable',
    ERROR: 'error',
};

const FILTER_INPUT_NODE_NAME = 'effect_input.music_control_eq';
const FILTER_OUTPUT_NODE_NAME = 'effect_output.music_control_eq';
const FILTER_DESCRIPTION = 'Music Control Equalizer';
const FILTER_SMART_NAME = 'music-control-equalizer';

/**
 * Real-time System-Wide Equalizer Backend powered by PipeWire Filter-Chain
 * and WirePlumber Smart Filter routing.
 */
export class PipeWireEqBackend extends EventEmitter {
    constructor() {
        super();

        this._status = BackendStatus.DISABLED;
        this._errorMessage = '';
        this._missingDeps = [];

        this._subprocess = null;
        this._cancellable = null;
        this._nodeId = null;

        this._bandGains = new Array(EQ_BANDS.length).fill(0.0);
        this._bassGain = 0.0;
        this._trebleGain = 0.0;

        this._debounceTimerId = 0;
        this._resolveTimerId = 0;
        this._restartTimerId = 0;
        this._updatingProps = false;
        this._pendingPropsUpdate = false;
        this._intentionallyStopped = true;

        this._runtimeDir = GLib.build_filenamev([
            GLib.get_user_runtime_dir(),
            'music-control-equalizer',
        ]);
        this._configPath = GLib.build_filenamev([
            this._runtimeDir,
            'filter-chain.conf',
        ]);

        this._checkDependencies();
    }

    get status() {
        return this._status;
    }

    get errorMessage() {
        return this._errorMessage;
    }

    get missingDependencies() {
        return [...this._missingDeps];
    }

    get isAvailable() {
        return this._missingDeps.length === 0;
    }

    get isReady() {
        return this._status === BackendStatus.READY && this._nodeId !== null;
    }

    _checkDependencies() {
        const required = ['pipewire', 'pw-cli', 'pw-dump'];
        this._missingDeps = required.filter(bin => !GLib.find_program_in_path(bin));
        if (this._missingDeps.length > 0) {
            this._setStatus(
                BackendStatus.UNAVAILABLE,
                `Missing required PipeWire tools: ${this._missingDeps.join(', ')}`
            );
        }
    }

    _setStatus(status, errorMessage = '') {
        const changed = this._status !== status || this._errorMessage !== errorMessage;
        this._status = status;
        this._errorMessage = errorMessage;
        if (changed)
            this.emit('status-changed', this._status, this._errorMessage);
    }

    /**
     * Build the PipeWire filter-chain configuration file contents.
     *
     * @returns {string}
     */
    _buildConfigContent() {
        const fmt = val => roundToStep(clamp(val, -12.0, 12.0), 0.1).toFixed(2);

        const nodes = [
            `                    { type = builtin name = ${BASS_NODE.nodeName}   label = ${BASS_NODE.label}  control = { "Freq" = ${BASS_NODE.freq.toFixed(1)} "Q" = ${BASS_NODE.q.toFixed(3)} "Gain" = ${fmt(this._bassGain)} } }`,
            `                    { type = builtin name = ${TREBLE_NODE.nodeName} label = ${TREBLE_NODE.label} control = { "Freq" = ${TREBLE_NODE.freq.toFixed(1)} "Q" = ${TREBLE_NODE.q.toFixed(3)} "Gain" = ${fmt(this._trebleGain)} } }`,
        ];

        for (let i = 0; i < EQ_BANDS.length; i++) {
            const band = EQ_BANDS[i];
            const gain = this._bandGains[i] ?? 0.0;
            nodes.push(
                `                    { type = builtin name = ${band.nodeName} label = ${band.label} control = { "Freq" = ${band.freq.toFixed(1)} "Q" = ${band.q.toFixed(3)} "Gain" = ${fmt(gain)} } }`
            );
        }

        const chainOrder = [
            BASS_NODE.nodeName,
            TREBLE_NODE.nodeName,
            ...EQ_BANDS.map(b => b.nodeName),
        ];

        const links = [];
        for (let i = 0; i < chainOrder.length - 1; i++) {
            links.push(
                `                    { output = "${chainOrder[i]}:Out" input = "${chainOrder[i + 1]}:In" }`
            );
        }

        return `# Auto-generated by Music Control & Equalizer GNOME Extension
context.properties = {
    log.level = 0
}

context.spa-libs = {
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}

context.modules = [
    { name = libpipewire-module-rt
        flags = [ ifexists nofail ]
    }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
    { name = libpipewire-module-filter-chain
        args = {
            node.description = "${FILTER_DESCRIPTION}"
            media.name       = "${FILTER_DESCRIPTION}"
            filter.graph = {
                nodes = [
${nodes.join('\n')}
                ]
                links = [
${links.join('\n')}
                ]
            }
            audio.channels = 2
            audio.position = [ FL FR ]
            capture.props = {
                node.name         = "${FILTER_INPUT_NODE_NAME}"
                media.class       = "Audio/Sink"
                filter.smart      = true
                filter.smart.name = "${FILTER_SMART_NAME}"
            }
            playback.props = {
                node.name    = "${FILTER_OUTPUT_NODE_NAME}"
                node.passive = true
            }
        }
    }
]
`;
    }

    /**
     * Start the PipeWire filter-chain process if not already running.
     *
     * @param {number[]} bandGains
     * @param {number} bassGain
     * @param {number} trebleGain
     */
    start(bandGains, bassGain, trebleGain) {
        if (Array.isArray(bandGains) && bandGains.length === EQ_BANDS.length)
            this._bandGains = bandGains.map(g => roundToStep(clamp(Number(g), -12.0, 12.0), 0.1));
        if (Number.isFinite(bassGain))
            this._bassGain = roundToStep(clamp(Number(bassGain), -12.0, 12.0), 0.1);
        if (Number.isFinite(trebleGain))
            this._trebleGain = roundToStep(clamp(Number(trebleGain), -12.0, 12.0), 0.1);

        this._checkDependencies();
        if (!this.isAvailable)
            return;

        if (this._subprocess) {
            this.applyGains(this._bandGains, this._bassGain, this._trebleGain, true);
            return;
        }

        this._intentionallyStopped = false;
        this._nodeId = null;
        this._cancellable = new Gio.Cancellable();
        this._setStatus(BackendStatus.STARTING);

        try {
            GLib.mkdir_with_parents(this._runtimeDir, 0o700);
            const content = this._buildConfigContent();
            GLib.file_set_contents(this._configPath, content);
        } catch (e) {
            Logger.error('Failed to write runtime filter-chain configuration', e);
            this._setStatus(BackendStatus.ERROR, 'Failed to write PipeWire filter configuration');
            return;
        }

        try {
            const launcher = new Gio.SubprocessLauncher({
                flags: Gio.SubprocessFlags.STDERR_PIPE | Gio.SubprocessFlags.STDOUT_SILENCE,
            });
            launcher.setenv('LC_ALL', 'C', true);
            launcher.setenv('LC_NUMERIC', 'C', true);

            const proc = launcher.spawnv(['pipewire', '-c', this._configPath]);
            this._subprocess = proc;

            proc.wait_async(this._cancellable, (source, res) => {
                try {
                    source.wait_finish(res);
                } catch (_e) {
                    // Cancelled during stop()
                }
                if (this._subprocess === source) {
                    this._subprocess = null;
                    this._nodeId = null;
                    if (!this._intentionallyStopped) {
                        Logger.warn('PipeWire filter-chain process exited unexpectedly; scheduling restart');
                        this._setStatus(BackendStatus.ERROR, 'PipeWire filter process exited');
                        this._scheduleRestart();
                    }
                }
            });

            this._resolveNodeIdWithRetry(0);
        } catch (e) {
            Logger.error('Failed to spawn pipewire filter-chain process', e);
            this._subprocess = null;
            this._setStatus(BackendStatus.ERROR, 'Failed to start PipeWire filter process');
        }
    }

    _scheduleRestart() {
        if (this._restartTimerId) {
            GLib.Source.remove(this._restartTimerId);
            this._restartTimerId = 0;
        }
        if (this._intentionallyStopped)
            return;

        this._restartTimerId = GLib.timeout_add(GLib.PRIORITY_DEFAULT, 1500, () => {
            this._restartTimerId = 0;
            if (!this._intentionallyStopped && !this._subprocess)
                this.start(this._bandGains, this._bassGain, this._trebleGain);
            return GLib.SOURCE_REMOVE;
        });
    }

    /**
     * Resolve the PipeWire node ID of `effect_input.music_control_eq` via `pw-dump`.
     *
     * @param {number} attempt
     */
    _resolveNodeIdWithRetry(attempt = 0) {
        if (this._resolveTimerId) {
            GLib.Source.remove(this._resolveTimerId);
            this._resolveTimerId = 0;
        }
        if (this._intentionallyStopped || !this._subprocess)
            return;

        const delayMs = attempt === 0 ? 180 : 250;
        this._resolveTimerId = GLib.timeout_add(GLib.PRIORITY_DEFAULT, delayMs, () => {
            this._resolveTimerId = 0;
            this._queryNodeId(attempt);
            return GLib.SOURCE_REMOVE;
        });
    }

    _queryNodeId(attempt) {
        if (this._intentionallyStopped || !this._subprocess)
            return;

        try {
            const launcher = new Gio.SubprocessLauncher({
                flags: Gio.SubprocessFlags.STDOUT_PIPE | Gio.SubprocessFlags.STDERR_SILENCE,
            });
            launcher.setenv('LC_ALL', 'C', true);
            const proc = launcher.spawnv(['pw-dump']);

            proc.communicate_utf8_async(null, this._cancellable, (source, res) => {
                try {
                    const [ok, stdout] = source.communicate_utf8_finish(res);
                    if (!ok || !stdout)
                        throw new Error('Empty output from pw-dump');

                    const objects = JSON.parse(stdout);
                    let foundId = null;
                    if (Array.isArray(objects)) {
                        for (const obj of objects) {
                            const nodeName = obj?.info?.props?.['node.name'];
                            if (nodeName === FILTER_INPUT_NODE_NAME && Number.isInteger(obj.id)) {
                                foundId = obj.id;
                                break;
                            }
                        }
                    }

                    if (foundId !== null) {
                        this._nodeId = foundId;
                        this._setStatus(BackendStatus.READY);
                        Logger.info(`PipeWire Equalizer node ready (node ID: ${foundId})`);
                        this._flushParamsToPipeWire();
                    } else if (attempt < 8) {
                        this._resolveNodeIdWithRetry(attempt + 1);
                    } else {
                        this._setStatus(BackendStatus.ERROR, 'Could not locate Equalizer node in PipeWire');
                    }
                } catch (e) {
                    if (this._intentionallyStopped)
                        return;
                    if (attempt < 8) {
                        this._resolveNodeIdWithRetry(attempt + 1);
                    } else {
                        Logger.error('Failed to resolve PipeWire Equalizer node ID', e);
                        this._setStatus(BackendStatus.ERROR, 'Failed to query PipeWire graph');
                    }
                }
            });
        } catch (e) {
            Logger.error('Failed to execute pw-dump', e);
            this._setStatus(BackendStatus.ERROR, 'Failed to run pw-dump');
        }
    }

    /**
     * Update Equalizer 10-band gains + Bass + Treble gains in real time.
     *
     * @param {number[]} bandGains
     * @param {number} bassGain
     * @param {number} trebleGain
     * @param {boolean} [immediate=false]
     */
    applyGains(bandGains, bassGain, trebleGain, immediate = false) {
        if (Array.isArray(bandGains) && bandGains.length === EQ_BANDS.length)
            this._bandGains = bandGains.map(g => roundToStep(clamp(Number(g), -12.0, 12.0), 0.1));
        if (Number.isFinite(bassGain))
            this._bassGain = roundToStep(clamp(Number(bassGain), -12.0, 12.0), 0.1);
        if (Number.isFinite(trebleGain))
            this._trebleGain = roundToStep(clamp(Number(trebleGain), -12.0, 12.0), 0.1);

        if (this._intentionallyStopped || !this._subprocess)
            return;

        if (this._nodeId === null) {
            this._pendingPropsUpdate = true;
            return;
        }

        if (immediate) {
            if (this._debounceTimerId) {
                GLib.Source.remove(this._debounceTimerId);
                this._debounceTimerId = 0;
            }
            this._flushParamsToPipeWire();
            return;
        }

        if (this._debounceTimerId)
            return;

        this._debounceTimerId = GLib.timeout_add(GLib.PRIORITY_DEFAULT, 25, () => {
            this._debounceTimerId = 0;
            this._flushParamsToPipeWire();
            return GLib.SOURCE_REMOVE;
        });
    }

    _flushParamsToPipeWire() {
        if (this._intentionallyStopped || !this._subprocess || this._nodeId === null)
            return;

        if (this._updatingProps) {
            this._pendingPropsUpdate = true;
            return;
        }

        this._updatingProps = true;
        this._pendingPropsUpdate = false;

        const fmt = val => roundToStep(clamp(val, -12.0, 12.0), 0.1).toFixed(2);
        const paramPairs = [
            `"${BASS_NODE.nodeName}:Gain" ${fmt(this._bassGain)}`,
            `"${TREBLE_NODE.nodeName}:Gain" ${fmt(this._trebleGain)}`,
        ];

        for (let i = 0; i < EQ_BANDS.length; i++) {
            const band = EQ_BANDS[i];
            const gain = this._bandGains[i] ?? 0.0;
            paramPairs.push(`"${band.nodeName}:Gain" ${fmt(gain)}`);
        }

        const propsArg = `{ params = [ ${paramPairs.join(' ')} ] }`;

        try {
            const launcher = new Gio.SubprocessLauncher({
                flags: Gio.SubprocessFlags.STDOUT_SILENCE | Gio.SubprocessFlags.STDERR_PIPE,
            });
            launcher.setenv('LC_ALL', 'C', true);
            launcher.setenv('LC_NUMERIC', 'C', true);

            const proc = launcher.spawnv([
                'pw-cli',
                's',
                String(this._nodeId),
                'Props',
                propsArg,
            ]);

            proc.wait_async(this._cancellable, (source, res) => {
                this._updatingProps = false;
                try {
                    source.wait_finish(res);
                    if (!source.get_successful() && !this._intentionallyStopped) {
                        // Node ID may have changed; re-resolve
                        this._nodeId = null;
                        this._resolveNodeIdWithRetry(0);
                        return;
                    }
                } catch (_e) {
                    return;
                }

                if (this._pendingPropsUpdate && !this._intentionallyStopped)
                    this._flushParamsToPipeWire();
            });
        } catch (e) {
            this._updatingProps = false;
            Logger.error('Failed to invoke pw-cli for parameter update', e);
        }
    }

    /**
     * Stop the PipeWire filter-chain subprocess and clean up runtime resources.
     */
    stop() {
        this._intentionallyStopped = true;

        if (this._debounceTimerId) {
            GLib.Source.remove(this._debounceTimerId);
            this._debounceTimerId = 0;
        }
        if (this._resolveTimerId) {
            GLib.Source.remove(this._resolveTimerId);
            this._resolveTimerId = 0;
        }
        if (this._restartTimerId) {
            GLib.Source.remove(this._restartTimerId);
            this._restartTimerId = 0;
        }

        if (this._cancellable) {
            this._cancellable.cancel();
            this._cancellable = null;
        }

        if (this._subprocess) {
            try {
                this._subprocess.force_exit();
            } catch (_e) {
                // Ignore if already exited
            }
            this._subprocess = null;
        }

        this._nodeId = null;
        this._updatingProps = false;
        this._pendingPropsUpdate = false;

        try {
            const file = Gio.File.new_for_path(this._configPath);
            if (file.query_exists(null))
                file.delete(null);
        } catch (_e) {
            // Ignore cleanup errors
        }

        if (this.isAvailable)
            this._setStatus(BackendStatus.DISABLED);
    }

    destroy() {
        this.stop();
        this.disconnectAll();
    }
}

/**
 * Hardware Audio Output & Volume Controller built on Gvc.MixerControl.
 */
export class SystemAudioController extends EventEmitter {
    constructor() {
        super();

        this._control = new Gvc.MixerControl({
            name: 'Music Control Equalizer Volume',
        });
        this._stream = null;
        this._streamSignalIds = [];
        this._controlSignalIds = [];

        this._devices = new Map();
        this._activeDeviceId = null;

        this._connectControlSignals();
        this._control.open();
    }

    _connectControlSignals() {
        const signals = [
            ['state-changed', () => this._onControlStateChanged()],
            ['default-sink-changed', () => this._updateDefaultSink()],
            ['output-added', (_c, id) => this._onOutputAdded(id)],
            ['output-removed', (_c, id) => this._onOutputRemoved(id)],
            ['active-output-update', (_c, id) => this._onActiveOutputUpdate(id)],
            ['stream-added', () => this._refreshCandidateOutputs()],
            ['stream-removed', () => this._refreshCandidateOutputs()],
        ];

        for (const [sig, handler] of signals) {
            const id = this._control.connect(sig, handler);
            this._controlSignalIds.push(id);
        }
    }

    _onControlStateChanged() {
        if (this._control.get_state() === Gvc.MixerControlState.READY) {
            this._updateDefaultSink();
            this._refreshCandidateOutputs();
        } else {
            this._setStream(null);
        }
        this.emit('state-changed', this._control.get_state());
    }

    _isEqualizerFilterDevice(device, stream = null) {
        if (!device)
            return true;
        const desc = (device.get_description() || '').toLowerCase();
        if (desc.includes('music control equalizer'))
            return true;

        const targetStream = stream || this._control.get_stream_from_device(device);
        const streamName = (targetStream?.get_name() || '').toLowerCase();
        if (streamName.includes('music_control_eq') || streamName.includes('music_eq'))
            return true;

        return false;
    }

    _onOutputAdded(id) {
        const dev = this._control.lookup_output_id(id);
        if (!dev || this._isEqualizerFilterDevice(dev))
            return;

        this._devices.set(id, this._createDeviceEntry(id, dev));
        this._syncActiveDeviceFromStream();
        this.emit('devices-changed');
    }

    _onOutputRemoved(id) {
        if (this._devices.delete(id))
            this.emit('devices-changed');
    }

    _onActiveOutputUpdate(id) {
        const dev = this._control.lookup_output_id(id);
        if (dev && !this._isEqualizerFilterDevice(dev)) {
            this._activeDeviceId = id;
            if (!this._devices.has(id))
                this._devices.set(id, this._createDeviceEntry(id, dev));
            this.emit('active-device-changed', this.getActiveDevice());
            this.emit('devices-changed');
        }
    }

    _refreshCandidateOutputs() {
        if (this._control.get_state() !== Gvc.MixerControlState.READY)
            return;

        // Probe output UI devices 1..32 so all hardware ports on the user's audio cards
        // (e.g. Headphones, Line Out, S/PDIF, HDMI) are selectable even if jack detection
        // marks them inactive.
        for (let id = 1; id <= 32; id++) {
            const dev = this._control.lookup_output_id(id);
            if (!dev || !dev.is_output() || this._isEqualizerFilterDevice(dev))
                continue;

            this._devices.set(id, this._createDeviceEntry(id, dev));
        }

        this._syncActiveDeviceFromStream();
        this.emit('devices-changed');
    }

    _createDeviceEntry(id, dev) {
        const description = dev.get_description() || 'Audio Output';
        const origin = dev.get_origin() || '';
        const fullLabel = origin ? `${description} – ${origin}` : description;
        const shortLabel = shortenDeviceName(description);
        const lower = `${description} ${origin}`.toLowerCase();

        let iconName = 'audio-speakers-symbolic';
        if (lower.includes('headphone') || lower.includes('headset') || lower.includes('earphone'))
            iconName = 'audio-headphones-symbolic';
        else if (lower.includes('hdmi') || lower.includes('displayport'))
            iconName = 'video-display-symbolic';
        else if (lower.includes('digital') || lower.includes('s/pdif') || lower.includes('iec958'))
            iconName = 'audio-card-symbolic';

        return {
            id,
            description,
            origin,
            fullLabel,
            shortLabel,
            iconName,
            portAvailable: Boolean(dev.port_available),
        };
    }

    _syncActiveDeviceFromStream() {
        if (!this._stream)
            return;

        const dev = this._control.lookup_device_from_stream(this._stream);
        if (dev && !this._isEqualizerFilterDevice(dev, this._stream)) {
            const id = dev.get_id();
            this._activeDeviceId = id;
            if (!this._devices.has(id))
                this._devices.set(id, this._createDeviceEntry(id, dev));
            this.emit('active-device-changed', this.getActiveDevice());
        }
    }

    _updateDefaultSink() {
        let sink = this._control.get_default_sink();
        if (sink && (sink.get_name() || '').includes('music_control_eq')) {
            // Find the actual hardware sink if the smart filter was ever returned
            const hardwareSink = this._control.get_sinks().find(
                s => !(s.get_name() || '').includes('music_control_eq')
            );
            if (hardwareSink)
                sink = hardwareSink;
        }
        this._setStream(sink);
    }

    _setStream(stream) {
        if (this._stream === stream)
            return;

        if (this._stream) {
            for (const id of this._streamSignalIds)
                this._stream.disconnect(id);
            this._streamSignalIds = [];
        }

        this._stream = stream;

        if (this._stream) {
            this._streamSignalIds.push(
                this._stream.connect('notify::volume', () => this.emit('volume-changed')),
                this._stream.connect('notify::is-muted', () => this.emit('volume-changed')),
                this._stream.connect('notify::port', () => {
                    this._refreshCandidateOutputs();
                    this._syncActiveDeviceFromStream();
                })
            );
            this._syncActiveDeviceFromStream();
        }

        this.emit('volume-changed');
    }

    /**
     * Get current normalized volume between 0.0 and 1.0 (or up to 1.5 if amplified).
     *
     * @returns {number}
     */
    getVolume() {
        if (!this._stream)
            return 0;
        if (this._stream.is_muted)
            return 0;

        const maxNorm = this._control.get_vol_max_norm();
        if (maxNorm <= 0)
            return 0;

        return clamp(this._stream.volume / maxNorm, 0, 1.5);
    }

    /**
     * Set normalized volume (0.0 to 1.0).
     *
     * @param {number} normalizedValue
     */
    setVolume(normalizedValue) {
        if (!this._stream)
            return;

        const clamped = clamp(normalizedValue, 0, 1.0);
        const maxNorm = this._control.get_vol_max_norm();
        const rawVolume = Math.round(clamped * maxNorm);

        const prevMuted = this._stream.is_muted;
        let changed = false;

        if (rawVolume < 1) {
            changed = this._stream.set_volume(0);
            if (!prevMuted)
                this._stream.change_is_muted(true);
        } else {
            changed = this._stream.set_volume(rawVolume);
            if (prevMuted)
                this._stream.change_is_muted(false);
        }

        if (changed)
            this._stream.push_volume();
    }

    getMuted() {
        if (!this._stream)
            return true;
        return Boolean(this._stream.is_muted || this._stream.volume === 0);
    }

    toggleMute() {
        if (!this._stream)
            return;

        const isMuted = this._stream.is_muted;
        if (isMuted && this._stream.volume === 0) {
            this._stream.set_volume(Math.round(0.25 * this._control.get_vol_max_norm()));
            this._stream.push_volume();
        }
        this._stream.change_is_muted(!isMuted);
    }

    getVolumeIconName() {
        if (!this._stream || this._stream.is_muted || this._stream.volume <= 0)
            return 'audio-volume-muted-symbolic';

        const level = this.getVolume();
        if (level > 1.0)
            return 'audio-volume-overamplified-symbolic';
        if (level >= 0.66)
            return 'audio-volume-high-symbolic';
        if (level >= 0.33)
            return 'audio-volume-medium-symbolic';
        return 'audio-volume-low-symbolic';
    }

    /**
     * Return sorted list of available hardware output devices.
     *
     * @returns {Array<{id: number, description: string, origin: string, fullLabel: string, shortLabel: string, iconName: string, isActive: boolean}>}
     */
    getOutputDevices() {
        const list = [];
        for (const [id, entry] of this._devices.entries()) {
            list.push({
                ...entry,
                isActive: id === this._activeDeviceId,
            });
        }

        // Put active device and portAvailable devices first
        list.sort((a, b) => {
            if (a.isActive !== b.isActive)
                return a.isActive ? -1 : 1;
            if (a.portAvailable !== b.portAvailable)
                return a.portAvailable ? -1 : 1;
            return a.id - b.id;
        });
        return list;
    }

    getActiveDevice() {
        if (this._activeDeviceId !== null && this._devices.has(this._activeDeviceId))
            return {...this._devices.get(this._activeDeviceId), isActive: true};

        if (this._stream) {
            const desc = this._stream.get_description() || 'Speakers';
            return {
                id: -1,
                description: desc,
                origin: '',
                fullLabel: desc,
                shortLabel: shortenDeviceName(desc),
                iconName: 'audio-headphones-symbolic',
                isActive: true,
            };
        }

        return {
            id: -1,
            description: 'Headphones',
            origin: '',
            fullLabel: 'Headphones',
            shortLabel: 'Headphones',
            iconName: 'audio-headphones-symbolic',
            isActive: true,
        };
    }

    /**
     * Switch active hardware output device by Gvc UI Device ID.
     *
     * @param {number} id
     */
    setActiveDevice(id) {
        const dev = this._control.lookup_output_id(id);
        if (!dev) {
            Logger.warn(`Cannot activate unknown audio output device ID ${id}`);
            return;
        }
        this._activeDeviceId = id;
        this._control.change_output(dev);
        this.emit('active-device-changed', this.getActiveDevice());
        this.emit('devices-changed');
    }

    destroy() {
        if (this._stream) {
            for (const id of this._streamSignalIds)
                this._stream.disconnect(id);
            this._streamSignalIds = [];
            this._stream = null;
        }

        if (this._control) {
            for (const id of this._controlSignalIds)
                this._control.disconnect(id);
            this._controlSignalIds = [];
            try {
                this._control.close();
            } catch (_e) {
                // Ignore
            }
            this._control = null;
        }

        this._devices.clear();
        this.disconnectAll();
    }
}
